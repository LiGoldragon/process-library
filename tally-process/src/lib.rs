//! The processes of the Tally Nexus: a sum, born of a call, and each of its
//! addends, born of the sum. Built with no operating system under it.
//!
//! A Sum gives one Addend process for each number it was called with; each
//! Addend gives one Add to the memory and ends with what it came to; the Sum
//! takes each Addend's end, and when the last has come it gives the caller the
//! total and ends. An Addend that overflows ends the Sum at once, and the
//! Addends still living are unwound with it.
//!
//! The types, the enums over the processes and what each process takes are
//! generated by ethos-zero from the roots in `ethos/`; what is written here is the
//! two bodies.

